void I2cInit(void)
{
	rcu_periph_clock_enable(RCU_I2C1);
	rcu_periph_clock_enable(RCU_GPIOB);

	gpio_init(GPIOB, GPIO_MODE_AF_OD, GPIO_OSPEED_50MHZ, GPIO_PIN_10 | GPIO_PIN_11);

	// I2C clock configure
	i2c_clock_config(I2C1, 400000, I2C_DTCY_2);
	// I2C address configure
	i2c_mode_addr_config(I2C1, I2C_I2CMODE_ENABLE, I2C_ADDFORMAT_7BITS, I2C1_SLAVE_ADDRESS7);
	// Enable I2C0
	i2c_enable(I2C1);
	// Enable acknowledge
	i2c_ack_config(I2C1, I2C_ACK_ENABLE);
}


void SSD1306_WriteCmd(uint8_t var)
{
	// Wait until I2C bus is idle
	while(i2c_flag_get(I2C1, I2C_FLAG_I2CBSY));
	// Send a start condition to I2C bus
	i2c_start_on_bus(I2C1);
	while(!i2c_flag_get(I2C1, I2C_FLAG_SBSEND));	// Wait until start bit is sent

	// Wait until the transmit data buffer is empty
	i2c_master_addressing(I2C1, SSD1306_ADDR << 1, I2C_TRANSMITTER); // Send device address and write data
	while(!i2c_flag_get(I2C1, I2C_FLAG_ADDSEND));
	i2c_flag_clear(I2C1, I2C_FLAG_ADDSEND);
	while(!i2c_flag_get(I2C1, I2C_FLAG_TBE));

	// Data transmission
	i2c_data_transmit(I2C1, 0x00);
	// Wait until the TI bit is set
	while(!i2c_flag_get(I2C1, I2C_FLAG_TBE));

	i2c_data_transmit(I2C1, var);
	// Wait until the TI bit is set
	while(!i2c_flag_get(I2C1, I2C_FLAG_TBE));

	// Wait for transfer complete flag
	while(!i2c_flag_get(I2C1, I2C_FLAG_BTC));
	// Send a stop condition to I2C bus
	i2c_stop_on_bus(I2C1);
}


void SSD1306_WriteData(uint8_t var)
{
	// Wait until I2C bus is idle
	while(i2c_flag_get(I2C1, I2C_FLAG_I2CBSY));
	// Send a start condition to I2C bus
	i2c_start_on_bus(I2C1);
	while(!i2c_flag_get(I2C1, I2C_FLAG_SBSEND));	// Wait for start condition to send

	// Wait until the transmit data buffer is empty
	i2c_master_addressing(I2C1, SSD1306_ADDR << 1, I2C_TRANSMITTER); // Send device address and write data
	while(!i2c_flag_get(I2C1, I2C_FLAG_ADDSEND));
	i2c_flag_clear(I2C1, I2C_FLAG_ADDSEND);
	while(!i2c_flag_get(I2C1, I2C_FLAG_TBE));

	// Data transmission
	i2c_data_transmit(I2C1, 0x40);
	// Wait until the TI bit is set
	while(!i2c_flag_get(I2C1, I2C_FLAG_TBE));

	i2c_data_transmit(I2C1, var);
	// Wait until the TI bit is set
	while(!i2c_flag_get(I2C1, I2C_FLAG_TBE));

	// Wait for transfer complete flag
	while(!i2c_flag_get(I2C1, I2C_FLAG_BTC));
	// Send a stop condition to I2C bus
	i2c_stop_on_bus(I2C1);
}


// Coordinate settings: where to display
void OledSetPos(uint8_t x, uint8_t y)
{
	if (x > MAX_COLUMN || y > 7)
	{
		return;
	}

	// The following 3 registers are valid only in page addressing mode.

	SSD1306_WriteCmd(0xb0 + y);					// Set page address (0-7)
	SSD1306_WriteCmd(((x >> 4) & 0x0f) | 0x10);	// Column high address setting
	SSD1306_WriteCmd(x & 0x0f);					// Column low address setting
}


// Enable OLED display
void OledDisplayOn(void)
{
	SSD1306_WriteCmd(0X8D);	// SET DCDC command
	SSD1306_WriteCmd(0X14);	// DCDC ON
	SSD1306_WriteCmd(0XAF);	// DISPLAY ON
}


// Turn off OLED display
void OledDisplayOff(void)
{
	SSD1306_WriteCmd(0X8D);	// SET DCDC command
	SSD1306_WriteCmd(0X10);	// DCDC OFF
	SSD1306_WriteCmd(0XAE);	// DISPLAY OFF
}


// Clears entire screen, making it all black as if it was not on
void OledClear(void)
{
	uint8_t i;
	uint16_t n;

	for(i = 0; i < 8; i++)
	{
		SSD1306_WriteCmd(0xb0 + i);		// Set page address (0-7)
		SSD1306_WriteCmd(0x00);			// Reset column low address
		SSD1306_WriteCmd(0x10);			// Reset column high address

		// Sweep through columns 0-127
		for(n = 0; n <= MAX_COLUMN; n++)
		{
			SSD1306_WriteData(0x00);    // Clear every pixel byte
		}
	}
}


void OledClearLine(uint8_t y)
{
	// Ensure y is within bounds
	if (y > 7)
	{
		return;
	}

	// Point cursor to start of target row
	SSD1306_WriteCmd(0xb0 + y);	// Set page address
	SSD1306_WriteCmd(0x00);		// Reset column low address
	SSD1306_WriteCmd(0x10);		// Reset column high address

	// Sweep through columns 0-127
	for (uint8_t n = 0; n <= MAX_COLUMN; n++)
	{
		SSD1306_WriteData(0x00);
	}
}

